export function showToast(message, type = 'info') {
  const container = document.getElementById('toastContainer');
  if (!container) return;

  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;
  
  let iconSvg = ICONS.sparkles;
  if (type === 'success') iconSvg = ICONS.check;
  if (type === 'danger') iconSvg = ICONS.trash;

  toast.innerHTML = `
    <span style="display:flex;align-items:center;color:${type === 'success' ? '#34d399' : type === 'danger' ? '#f87171' : '#818cf8'}">
      ${iconSvg}
    </span>
    <span>${message}</span>
  `;

  container.appendChild(toast);

  setTimeout(() => {
    toast.style.opacity = '0';
    toast.style.transform = 'translateY(-10px)';
    toast.style.transition = 'all 0.3s ease';
    setTimeout(() => toast.remove(), 300);
  }, 2600);
}

/**
 * Mobile Bottom Sheet Modal
 */
export function openSheet(title, contentHtml) {
  const overlay = document.getElementById('sheetOverlay');
  const sheetTitle = document.getElementById('sheetTitle');
  const sheetBody = document.getElementById('sheetBody');

  sheetTitle.textContent = title;
  sheetBody.innerHTML = contentHtml;
  overlay.classList.add('open');
}

export function closeSheet() {
  const overlay = document.getElementById('sheetOverlay');
  overlay.classList.remove('open');
}

/**
 * Fullscreen Photo Viewer
 */
export function openViewer(photo, onTrash) {
  const modal = document.getElementById('viewerModal');
  const viewerImg = document.getElementById('viewerImg');
  const viewerName = document.getElementById('viewerName');
  const viewerSize = document.getElementById('viewerSize');
  const viewerRes = document.getElementById('viewerRes');
  const viewerDeleteBtn = document.getElementById('viewerDeleteBtn');

  const fullUrl = URL.createObjectURL(photo.blob);
  viewerImg.src = fullUrl;
  viewerName.textContent = photo.name;
  viewerSize.textContent = `${(photo.size / (1024 * 1024)).toFixed(2)} MB`;
  viewerRes.textContent = `${photo.width} × ${photo.height} px`;

  viewerDeleteBtn.onclick = () => {
    if (onTrash) onTrash(photo.id);
    closeViewer();
  };

  modal.classList.add('open');

  const handleClose = () => {
    URL.revokeObjectURL(fullUrl);
    modal.classList.remove('open');
  };

  document.getElementById('viewerCloseBtn').onclick = handleClose;
}

export function closeViewer() {
  const modal = document.getElementById('viewerModal');
  modal.classList.remove('open');
}
